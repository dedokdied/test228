-- Лабораторная работа № 3. Схема БД (code-first + Flyway).
-- Таблица товаров магазина электроники.

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255)   NOT NULL,
    brand          VARCHAR(255)   NOT NULL,
    price          NUMERIC(12, 2) NOT NULL,
    count_in_stock INTEGER        NOT NULL,
    CONSTRAINT chk_products_price CHECK (price > 0),
    CONSTRAINT chk_products_count CHECK (count_in_stock >= 0)
);

CREATE INDEX idx_products_brand ON products (LOWER(brand));
CREATE INDEX idx_products_price ON products (price);

-- Пользователи API (аутентификация и ролевая модель).
CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT chk_app_users_role CHECK (role IN ('ADMIN', 'USER'))
);

CREATE INDEX idx_app_users_username ON app_users (username);
